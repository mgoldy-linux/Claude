SELECT 'Check1_UnmatchedItemId' AS CheckName, COUNT(*) AS Cnt
FROM #PrimaryBinUpdates u
LEFT JOIN inv_mast im ON im.item_id = u.item_id
WHERE im.inv_mast_uid IS NULL

UNION ALL

SELECT 'Check2_NoInvLocAt221', COUNT(*)
FROM #PrimaryBinUpdates u
JOIN inv_mast im ON im.item_id = u.item_id
LEFT JOIN inv_loc il ON il.inv_mast_uid = im.inv_mast_uid AND il.location_id = 221
WHERE il.inv_mast_uid IS NULL

UNION ALL

SELECT 'Check3_TargetBinNoLongerHasStock', COUNT(*)
FROM #PrimaryBinUpdates u
JOIN inv_mast im ON im.item_id = u.item_id
LEFT JOIN inv_bin ib ON ib.inv_mast_uid = im.inv_mast_uid AND ib.location_id = 221 AND ib.bin = u.new_bin
WHERE ib.inv_mast_uid IS NULL

UNION ALL

SELECT 'StillNOBIN', COUNT(*)
FROM #PrimaryBinUpdates u
JOIN inv_mast im ON im.item_id = u.item_id
JOIN inv_loc il ON il.inv_mast_uid = im.inv_mast_uid AND il.location_id = 221
WHERE il.primary_bin = 'NOBIN'

UNION ALL

SELECT 'AlreadyMatchesTarget', COUNT(*)
FROM #PrimaryBinUpdates u
JOIN inv_mast im ON im.item_id = u.item_id
JOIN inv_loc il ON il.inv_mast_uid = im.inv_mast_uid AND il.location_id = 221
WHERE il.primary_bin = u.new_bin;

