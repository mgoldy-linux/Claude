  *** WHY THIS IS SQL AND NOT THE CLIENT ***
  Saving an alert in Alert Maintenance REGENERATES the entire where_clause from
  the Filter grid (trap 10). uid 106's -5% OR trigger has no grid representation.
  A scoped UPDATE on alert_message.footer touches only that column and cannot
  disturb any trigger, so it is the safe route for all of them.

  footer is a `text` column: every read and REPLACE CASTs to varchar(max) first.
  A Prod-only text/nvarchar(max) CAST bug bit script 10's guard clauses, hence
  the explicit casts in the WHERE as well. Line breaks in these footers are CRLF
  (verified on both environments 2026-10-06), so the inserted blank line uses
  CHAR(13)+CHAR(10).

  Idempotent: guarded on 'customermaintenance' not already being present.
